def org_doc_name(doc: dict, taken=()) -> str:
    """기관 보관 문서의 인용 이름. "기관보관/보고서/제목" — 화면 출처 칩도 이 이름을 쓴다.

    보관 파일명은 결재란 글자("부장")처럼 엉뚱한 경우가 많아 본문에서 제목을 다시 뽑는다.
    """
    stem = re.sub(r"^\d{8}-\d{6}-", "", doc.get("name", ""))
    stem = re.sub(r"(-[0-9a-f]{10})?\.txt$", "", stem)
    # 인수인계 때 올라온 자료는 원본 파일명이 곧 제목이다(엑셀·메일은 본문 첫 줄이 제목이 아님)
    if "인수인계" in doc.get("type", "") and stem:
        title = stem
    else:
        title = extract_title(doc.get("text", ""), stem or "문서")
    title = re.sub(r"[\[\],/]", " ", title).strip()[:40] or "문서"
    name = f"기관보관/{doc.get('type', '문서')}/{title}"
    # 제목이 겹치면 보관일을 붙여 구분한다
    if name in taken and doc.get("saved"):
        name = f"{name} ({doc['saved']})"
    return name


def build_handover_input(files: list, note: str = "", org_docs=()) -> str:
    """[{name, text}] → 자료 구분선이 붙은 하나의 입력 텍스트.

    너무 긴 자료는 잘라내고 잘렸다는 표시를 남긴다(모델이 '없는 내용'으로 오해하지 않게).
    org_docs: [{cite, saved, text}] — 기관 보관 문서 중 관련 있는 것(보조 자료, 맨 뒤에 붙음).
    """
    parts, total = [], 0
    for i, f in enumerate(files, 1):
        name = (f.get("name") or f"자료{i}").strip()
        text = (f.get("text") or "").strip()
        if not text:
            continue
        if len(text) > HANDOVER_MAX_FILE_CHARS:
            text = text[:HANDOVER_MAX_FILE_CHARS] + "\n(이하 분량이 많아 생략)"
        if total + len(text) > HANDOVER_MAX_TOTAL_CHARS:
            parts.append(f"===== [자료 {i}] {name} =====\n(전체 분량 한도를 넘어 생략)")
            continue
        total += len(text)
        parts.append(f"===== [자료 {i}] {name} =====\n{text}")
    for i, d in enumerate(org_docs, 1):
        saved = f"(보관일 {d['saved']})\n" if d.get("saved") else ""
        parts.append(f"===== [기관 보관 {i}] {d['cite']} =====\n{saved}"
                     f"{d['text'][:HANDOVER_ORG_DOC_CHARS]}")
    body = "\n\n".join(parts)
    if note.strip():
        body = f"[전임자 메모]\n{note.strip()}\n\n{body}"
    return body


