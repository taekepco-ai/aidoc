WRITE_TEMPLATES = {
    "공문-외부": (TEMPLATE_LETTER_EXT, "letter"),
    "공문-내부":     (TEMPLATE_LETTER_INT, "letter"),
    "보고서":        (TEMPLATE_REPORT,     "report"),
}

REVIEW_TEMPLATES = {
    "공문-외부": (TEMPLATE_REVIEW_LETTER_EXT, "letter"),
    "공문-내부":     (TEMPLATE_REVIEW_LETTER_INT, "letter"),
    "보고서":        (TEMPLATE_REVIEW_REPORT,     "report"),
}


def get_system_prompt(task: str, doc_type: str, org: dict,
                      references: list | None = None,
                      custom_format: str | None = None) -> str:
    """task: "write" | "review", doc_type: DOC_TYPES 중 하나, org: core.orgs 의 dict.

    references: 기관 보관 문서 목록(본문 문자열 또는 dict, _reference_block 참고).
                작성 시 참고 자료로 덧붙인다.
    """
    if task == "summary":
        return SUMMARY_PROMPT

    year = datetime.now().year
    if task == "handover":
        return HANDOVER_PROMPT.format(
            org_title=_org_title(org), org_block=_org_block(org, "report"),
            year=year,
        )
    if task == "review":
        # 검토는 유형을 미리 받지 않는다. AI 가 판정하고 그 기준으로 검토한다.
        return (REVIEW_AUTO.format(
            org_title=_org_title(org), org_block=_org_block(org, "report"),
            year=year, yy=f"{year % 100:02d}",
        ) + "\n\n" + REVIEW_COMMON)

    table = WRITE_TEMPLATES
    if doc_type not in table:
        raise ValueError(f"알 수 없는 문서 유형: {doc_type}")

    template, kind = table[doc_type]
    prompt = template.format(
        org_title=_org_title(org),
        org_block=_org_block(org, kind),
        year=year,
        yy=f"{year % 100:02d}",   # 템플릿에 어깨점(')이 이미 있으므로 숫자만
    )
    # 한글 저장 서식에 맞춘 줄 길이·표 규칙 (kanana-doc 과 같은 기준)
    prompt += "\n\n" + LINE_NOTE + "\n\n" + TABLE_NOTE

    # 우선순위: 기관이 직접 정의한 양식 > 그 기관의 실제 문서 > 위 기본 규칙
    if custom_format:
        prompt += "\n\n" + _format_block(custom_format)
    if references:
        prompt += "\n\n" + _reference_block(references, task)
    return prompt


def _format_block(spec: str) -> str:
    """datas/<기관>/<유형>/양식.md 의 내용. 기본 규칙보다 우선한다."""
    return (
        "[★ 이 기관이 정한 양식 — 최우선]\n"
        "아래는 이 기관에서 직접 정의한 이 문서 유형의 양식입니다.\n"
        "위에 적힌 기본 양식·항목 기호와 어긋나면 반드시 아래를 따르세요.\n"
        "아래에 언급되지 않은 부분만 위 기본 규칙을 적용합니다.\n\n"
        + spec.strip()
    )


def _reference_block(references: list, task: str) -> str:
    """기관에 보관된 실제 문서를 참고 자료로 덧붙인다.

    references: 본문 문자열, 또는 {"text", "type", "cite", "related"} dict.
      related=True  요청 내용과 관련 있어 고른 문서(공문·보고서·인수인계 자료 섞임)
      related=False 관련 문서가 없어 같은 유형 최근 문서를 양식 참고로만 붙인 것
    양식은 법정 표준이 아니라 기관마다 다른 관행이므로, 위에 적힌 규칙보다
    이 기관이 실제로 쓰는 문서가 더 정확한 기준이다.
    """
    docs = [r if isinstance(r, dict) else {"text": r} for r in references]
    samples = []
    for i, d in enumerate(docs, 1):
        label = d.get("cite") or (f"{d['type']} 문서" if d.get("type") else "")
        head_line = f"--- 참고 {i} · {label} ---" if label else f"--- 참고 {i} ---"
        samples.append(head_line + "\n" + d["text"].strip())

    if task == "review":
        head = (
            "[이 기관의 실제 문서]\n"
            "아래는 이 기관에서 실제로 사용한 같은 유형의 문서입니다.\n"
            "양식과 항목 기호는 기관마다 다른 관행이므로, 위 검토 기준과 아래 실제\n"
            "문서가 어긋나면 아래 실제 문서 쪽을 기준으로 판단하세요.\n"
            "실제 문서에서 통용되는 표기를 위반이라고 지적하지 마세요.\n\n"
        )
    elif any(d.get("related") for d in docs):
        head = (
            "[이 기관의 관련 문서]\n"
            "아래는 이 기관에 보관된 문서(공문·보고서·인수인계 자료) 중 요청 내용과 관련 있는 것입니다.\n"
            "- 요청과 같은 유형의 문서가 있으면 항목 구성·표기 방식·문체를 따른다.\n"
            "- 배경·경과·기관명·부서명·전년 일정처럼 요청과 직접 관련된 사실은 참고해 써도 된다.\n"
            "- 사용자가 요청하지 않은 사업·수치·일정을 새로 끌어와 넣지 않는다. 문장을 그대로 베끼지 않는다.\n"
            "- 참고 문서와 요청이 어긋나면 요청을 따른다.\n\n"
        )
    else:
        head = (
            "[이 기관의 실제 문서]\n"
            "아래는 이 기관에서 실제로 사용한 같은 유형의 문서입니다.\n"
            "항목 구성, 표기 방식, 문체를 참고하되 내용을 그대로 베끼지 마세요.\n"
            "사용자가 요청한 내용만 작성해야 합니다.\n\n"
        )
    return head + "\n\n".join(samples)


