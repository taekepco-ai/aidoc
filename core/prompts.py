def _org_title(org: dict) -> str:
    """'한국전력공사(한전, KEPCO)' 형태의 호칭."""
    name = org["name"]
    tags = [t for t in (org.get("short"), org.get("alias")) if t and t != name]
    # 중복 제거 (short 와 alias 가 같은 경우)
    seen, uniq = set(), []
    for t in tags:
        if t not in seen:
            seen.add(t)
            uniq.append(t)
    return f"{name}({', '.join(uniq)})" if uniq else name


def _org_block(org: dict, kind: str) -> str:
    """[조직 정보] 블록. kind: 'letter' | 'report'"""
    short = org.get("short") or org["name"]
    self_ref = org.get("self_ref") or "우리 기관"

    ref = f'본문에서 "{self_ref}"'
    if short != org["name"]:
        ref += f' 또는 "{short}"'
    ref += "으로 지칭"

    lines = [
        "[조직 정보]",
        f"- 기관: {org['name']} ({ref})",
        f"- 시점: {datetime.now().year}년",
    ]
    key = "departments_report" if kind == "report" else "departments_letter"
    departments = org.get(key) or []
    if departments:
        lines.append(f"- 부서명 예시: {', '.join(departments)} 등")
    return "\n".join(lines)


