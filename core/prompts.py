_TITLE_RE = re.compile(r"^제\s*목\s+(.+)$", re.MULTILINE)


_SUMMARY_TYPE_RE = re.compile(r"^\[유형\]\s*(공문-외부|공문-내부|보고서)\b[^\n]*")


def parse_summary_type(text: str):
    """요약 출력 첫 줄의 "[유형] ○○" 을 읽는다.

    (분류된 유형 또는 None, 유형 줄을 제거한 요약 본문) 을 돌려준다.
    """
    stripped = (text or "").lstrip()
    m = _SUMMARY_TYPE_RE.match(stripped)
    if m:
        return m.group(1), stripped[m.end():].lstrip("\n").lstrip()
    return None, text


_MATCH_MARK = "###유형일치###"
_MISMATCH_MARK = "###유형불일치###"


def parse_type_verdict(text: str):
    """검토 출력 첫 줄의 유형 판정 마커를 읽는다.

    (일치 여부, 마커를 제거한 본문) 을 돌려준다.
    마커가 없으면 일치로 간주한다(정상 검토를 막지 않도록).
    """
    stripped = (text or "").lstrip()
    if stripped.startswith(_MISMATCH_MARK):
        return False, stripped[len(_MISMATCH_MARK):].lstrip("\n").lstrip()
    if stripped.startswith(_MATCH_MARK):
        return True, stripped[len(_MATCH_MARK):].lstrip("\n").lstrip()
    return True, text


# 결재란·문서 메타데이터 셀 (제목으로 부적합). 공백 제거 후 비교.
_META_TITLE_WORDS = {
    "부장", "처장", "본부장", "실장", "단장", "과장", "차장", "팀장", "사장",
    "원장", "이사", "합의", "결재", "협조", "시행", "접수",
    "문서번호", "등록일", "보존기간", "보존년한", "공개구분", "공개", "수신자",
}


def extract_title(text: str, fallback: str = "문서") -> str:
    """제목을 뽑는다. 공문은 "제목 ..." 줄, 그 외엔 첫 '의미 있는' 줄.

    결재란·문서번호·표 행·AI 서두·날짜 줄은 건너뛴다(파일명 오염 방지).
    """
    m = _TITLE_RE.search(text or "")
    if m:
        return m.group(1).strip()

    for line in (text or "").splitlines():
        line = line.strip()
        if len(line) < 4:                              # 너무 짧은 줄(결재란 셀 등)
            continue
        if "|" in line:                                # 표 행
            continue
        if re.match(r"^-{2,}", line) or re.match(r"^={2,}", line):
            continue
        if re.match(r"^---\s*\d+\s*페이지", line):      # PDF 페이지 표시
            continue
        if re.match(r"^(수신|발신|참조)\b", line):
            continue
        if re.match(r"^[\d'\s.\-~()요일월년]+$", line):  # 날짜·숫자만
            continue
        if re.match(r"^\d+\s*[.)]", line):             # "1." "2)" 섹션 번호
            continue
        if line[0] in "#*•-□○◦❚※☞◈⊙◉":                 # 마크다운·장식 기호로 시작
            continue
        compact = line.replace(" ", "")
        if compact in _META_TITLE_WORDS:               # 결재란/메타 단어
            continue
        if re.match(r"^(네|예|안녕하세요|알겠습니다|아래|다음은|물론)[,.\s]", line):
            continue                                   # AI 서두
        return line[:60]
    return fallback


